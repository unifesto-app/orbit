// Regenerates src/app/duotone.tsx from Phosphor's duotone icons (MIT) via the Iconify API, as web/scripts/icons.mjs
// does for the web: the side nav's coloured icons (owner, 17 Nov 2026: "bring icons too with various accents ( duotone )").
// Galaxy's own 16px stroke icons (src/app/icons.tsx) stay for the chrome. To add one: add `name: "phosphor-name-duotone"`
// below, then run `node galaxy/scripts/icons.mjs`. Browse names at https://phosphoricons.com (duotone weight).
import { writeFileSync } from "node:fs";

const icons = {
  people: "users-three-duotone",
  users: "user-duotone",
  hosts: "storefront-duotone",
  venues: "map-pin-area-duotone",
  artists: "microphone-stage-duotone",
  teams: "users-four-duotone",
  speakers: "chalkboard-teacher-duotone",
  attendees: "ticket-duotone",
  staff: "identification-badge-duotone",
  events: "calendar-blank-duotone",
};

const res = await fetch(`https://api.iconify.design/ph.json?icons=${Object.values(icons).join(",")}`);
const data = await res.json();
if (data.not_found) throw new Error(`Not in Phosphor: ${data.not_found.join(", ")}`);

// Every Phosphor duotone icon is a 20% tint path under a solid path; refuse anything else.
const shape = /^<g fill="currentColor"><path d="([^"]+)" opacity="\.2"\/><path d="([^"]+)"\/><\/g>$/;
const entries = Object.entries(icons).map(([key, name]) => {
  const m = data.icons[name].body.match(shape);
  if (!m) throw new Error(`Unexpected markup in ${name}`);
  return `  // ${name}\n  ${key}: [\n    "${m[1]}",\n    "${m[2]}",\n  ],`;
});

writeFileSync(
  new URL("../src/app/duotone.tsx", import.meta.url),
  `// Generated by galaxy/scripts/icons.mjs. Do not edit by hand.
// Phosphor Icons, duotone weight (https://phosphoricons.com), MIT licence: no on-site credit needed.
// Each icon is [20% tint layer, solid layer].
const paths = {
${entries.join("\n")}
} as const;

export type DuotoneName = keyof typeof paths;

// Duotone, 256 x 256 grid; both layers take their colour from CSS (currentColor).
export function Duotone({ name, size = 16, className }: { name: DuotoneName; size?: number; className?: string }) {
  const [tint, solid] = paths[name];
  return (
    <svg className={className} width={size} height={size} viewBox="0 0 256 256" fill="currentColor" aria-hidden="true">
      <path d={tint} opacity={0.2} />
      <path d={solid} />
    </svg>
  );
}
`,
);
console.log(`duotone.tsx: ${Object.keys(icons).join(", ")}`);
