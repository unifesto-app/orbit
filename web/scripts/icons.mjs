// Regenerates src/app/icons.tsx from Phosphor's duotone icons (MIT) via the Iconify API.
// To add an icon: add `name: "phosphor-name-duotone"` below, then run `node web/scripts/icons.mjs`.
// Browse names at https://phosphoricons.com (pick the duotone weight).
import { writeFileSync } from "node:fs";

const icons = {
  pin: "map-pin-duotone",
  search: "magnifying-glass-duotone",
  calendar: "calendar-blank-duotone",
  back: "arrow-left-duotone",
  code: "code-duotone",
  comedy: "microphone-stage-duotone",
  music: "music-notes-duotone",
  group: "users-three-duotone",
  workshop: "chalkboard-teacher-duotone",
  fest: "confetti-duotone",
  sports: "soccer-ball-duotone",
  theatre: "mask-happy-duotone",
  art: "palette-duotone",
  film: "film-slate-duotone",
  startup: "rocket-launch-duotone",
  gaming: "game-controller-duotone",
  repeat: "repeat-duotone",
  college: "graduation-cap-duotone",
  cafe: "coffee-duotone",
  society: "buildings-duotone",
  company: "briefcase-duotone",
};

const res = await fetch(`https://api.iconify.design/ph.json?icons=${Object.values(icons).join(",")}`);
const data = await res.json();
if (data.not_found) throw new Error(`Not in Phosphor: ${data.not_found.join(", ")}`);

// Every Phosphor duotone icon is a 20% tint path under a solid path; refuse anything else.
const shape = /^<g fill="currentColor"><path d="([^"]+)" opacity="\.2"\/><path d="([^"]+)"\/><\/g>$/;
const entries = Object.entries(icons).map(([key, name]) => {
  const m = data.icons[name].body.match(shape);
  if (!m) throw new Error(`Unexpected markup in ${name}`);
  return `  // ${name}\n  ${key}: [\n    "${m[1]}",\n    "${m[2]}",\n  ],`;
});

writeFileSync(
  new URL("../src/app/icons.tsx", import.meta.url),
  `// Generated by web/scripts/icons.mjs. Do not edit by hand.
// Phosphor Icons, duotone weight (https://phosphoricons.com), MIT licence: no on-site credit needed.
// Each icon is [20% tint layer, solid layer].
const paths = {
${entries.join("\n")}
} as const;

export type IconName = keyof typeof paths;

// Duotone, 256 x 256 grid; both layers take their colour from CSS (currentColor).
export function Icon({ name, size = 24, className }: { name: IconName; size?: number; className?: string }) {
  const [tint, solid] = paths[name];
  return (
    <svg className={className} width={size} height={size} viewBox="0 0 256 256" fill="currentColor" aria-hidden="true">
      <path d={tint} opacity={0.2} />
      <path d={solid} />
    </svg>
  );
}
`,
);
console.log(`icons.tsx: ${Object.keys(icons).join(", ")}`);
